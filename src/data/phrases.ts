function assertCatalogSize() {
  const invalid = Object.entries(catalog).filter(([, phrases]) => phrases.length !== 20)
  if (invalid.length > 0) {
    const ids = invalid.map(([id]) => id).join(', ')
    throw new Error(`Каждая ситуация должна содержать 20 фраз. Ошибка в: ${ids}`)
  }
}

assertCatalogSize()

export const phrases: Phrase[] = Object.entries(catalog).flatMap(([situationId, seeds]) =>
  seeds.map((seed, index) => {
    const itemNumber = String(index + 1).padStart(2, '0')

    return {
      id: `${situationId}-${itemNumber}`,
      situationId,
      level: seed.level,
      de: seed.de,
      ru: seed.ru,
      translitRu: transliterateGermanToRu(seed.de),
      audioDeSrc: `/audio/${situationId}-${itemNumber}.mp3`,
      tags: [seed.level, situationId],
    }
  }),
)

export const phrasesBySituation = phrases.reduce<Record<string, Phrase[]>>((acc, phrase) => {
  acc[phrase.situationId] = acc[phrase.situationId] ?? []
  acc[phrase.situationId].push(phrase)
  return acc
}, {})

export const phraseById = new Map(phrases.map((phrase) => [phrase.id, phrase]))
